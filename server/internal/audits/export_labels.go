func formatAuditModule(mod string) string {
	if mod == "" {
		return ""
	}
	if label, ok := auditModuleLabels[mod]; ok {
		return label
	}
	if label, ok := auditModuleLabels[strings.ToLower(strings.TrimSpace(mod))]; ok {
		return label
	}
	return mod
}

func formatAuditAction(action string) string {
	if action == "" {
		return ""
	}
	if label, ok := auditActionLabels[action]; ok {
		return label
	}
	trimmed := strings.TrimSpace(action)
	if label, ok := auditActionLabels[strings.ToLower(trimmed)]; ok {
		return label
	}
	if label, ok := auditActionLabels[strings.ToUpper(trimmed)]; ok {
		return label
	}
	return action
}

