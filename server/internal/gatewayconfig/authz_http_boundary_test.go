// authzAdminPipeListener gives this process a real net/http server boundary
// without requiring an OS socket, which is unavailable in the isolated test
// environment.
type authzAdminPipeListener struct {
	conns     chan net.Conn
	done      chan struct{}
	closeOnce sync.Once
}

type authzAdminPipeAddr struct{}

func (authzAdminPipeAddr) Network() string { return "authz-admin-pipe" }
func (authzAdminPipeAddr) String() string  { return "authz-admin-pipe" }

func newAuthzAdminPipeListener() *authzAdminPipeListener {
	return &authzAdminPipeListener{conns: make(chan net.Conn), done: make(chan struct{})}
}

func (l *authzAdminPipeListener) Accept() (net.Conn, error) {
	select {
	case conn := <-l.conns:
		return conn, nil
	case <-l.done:
		return nil, net.ErrClosed
	}
}

func (l *authzAdminPipeListener) Close() error {
	l.closeOnce.Do(func() { close(l.done) })
	return nil
}

func (l *authzAdminPipeListener) Addr() net.Addr { return authzAdminPipeAddr{} }

func (l *authzAdminPipeListener) dial(ctx context.Context, _, _ string) (net.Conn, error) {
	clientConn, serverConn := net.Pipe()
	select {
	case l.conns <- serverConn:
		return clientConn, nil
	case <-l.done:
		_ = clientConn.Close()
		_ = serverConn.Close()
		return nil, net.ErrClosed
	case <-ctx.Done():
		_ = clientConn.Close()
		_ = serverConn.Close()
		return nil, ctx.Err()
	}
}

type authzPublishedContract struct {
	AppID            string          `json:"app_id"`
	GuardConfig      GuardConfig     `json:"guard_config"`
	CandidateHandoff json.RawMessage `json:"candidate_handoff"`
}

// TestAuthzProviderConfigHTTPBoundary exercises the Provider-to-Caddy boundary
// as an independent server process. The input is generated by guardconfig's
// Provider test; CaddyClient then uses its production GET /config/ and POST
// /load methods against a live net/http.Server, and the exact loaded payload
// is handed to the separate gateway process.
func TestAuthzProviderConfigHTTPBoundary(t *testing.T) {
	in := os.Getenv("AUTHZ_CONTRACT_INPUT")
	out := os.Getenv("AUTHZ_CADDY_CONFIG_OUTPUT")
	if in == "" || out == "" {
		t.Skip("AUTHZ_CONTRACT_INPUT and AUTHZ_CADDY_CONFIG_OUTPUT are required")
	}
	data, err := os.ReadFile(in)
	if err != nil {
		t.Fatalf("read Provider contract: %v", err)
	}
	var contract authzPublishedContract
	if err := json.Unmarshal(data, &contract); err != nil {
		t.Fatalf("decode Provider contract: %v", err)
	}
	if contract.AppID == "" || len(contract.GuardConfig.APIAuthzModels) == 0 {
		t.Fatalf("Provider contract missing application or authz models: app=%q models=%d", contract.AppID, len(contract.GuardConfig.APIAuthzModels))
	}
	if contract.GuardConfig.APIAuthzObjectHMACKeyHex == "" || contract.GuardConfig.APIAuthzPreviousValid == nil {
		t.Fatal("Provider contract missing current or PreviousValid authz key")
	}
	if len(contract.CandidateHandoff) == 0 || string(contract.CandidateHandoff) == "null" {
		t.Fatal("Provider contract missing candidate confirmation handoff")
	}

	previousJSON := `{"apps":{"contract":{"version":"previous"}}}`
	var received string
	var receivedContentType string
	currentJSON := previousJSON
	var mu sync.Mutex
	mux := http.NewServeMux()
	mux.HandleFunc("GET /config/", func(w http.ResponseWriter, _ *http.Request) {
		mu.Lock()
		current := currentJSON
		mu.Unlock()
		w.Header().Set("Content-Type", "application/json")
		_, _ = io.WriteString(w, current)
	})
	mux.HandleFunc("POST /load", func(w http.ResponseWriter, r *http.Request) {
		body, readErr := io.ReadAll(r.Body)
		if readErr != nil {
			http.Error(w, readErr.Error(), http.StatusBadRequest)
			return
		}
		if r.Header.Get("Content-Type") != "application/json" {
			http.Error(w, "content type must be application/json", http.StatusBadRequest)
			return
		}
		var decoded map[string]json.RawMessage
		if err := json.Unmarshal(body, &decoded); err != nil {
			http.Error(w, "invalid json", http.StatusBadRequest)
			return
		}
		if _, ok := decoded["guard_config"]; !ok {
			http.Error(w, "guard_config missing", http.StatusBadRequest)
			return
		}
		mu.Lock()
		received = string(body)
		receivedContentType = r.Header.Get("Content-Type")
		currentJSON = received
		mu.Unlock()
		w.WriteHeader(http.StatusOK)
	})

	listener := newAuthzAdminPipeListener()
	server := &http.Server{Handler: mux}
	serveErr := make(chan error, 1)
	go func() { serveErr <- server.Serve(listener) }()
	t.Cleanup(func() {
		shutdownCtx, cancel := context.WithTimeout(context.Background(), time.Second)
		defer cancel()
		_ = server.Shutdown(shutdownCtx)
		select {
		case err := <-serveErr:
			if err != nil && !errors.Is(err, http.ErrServerClosed) {
				t.Errorf("gatewayconfig HTTP server: %v", err)
			}
		case <-time.After(time.Second):
			t.Error("gatewayconfig HTTP server did not stop")
		}
	})

	transport := &http.Transport{DialContext: func(ctx context.Context, _, _ string) (net.Conn, error) {
		return listener.dial(ctx, "", "")
	}}
	client := &CaddyClient{
		baseURL: "http://authz-admin.test",
		httpClient: &http.Client{
			Transport: transport,
			Timeout:   time.Second,
		},
	}
	t.Cleanup(transport.CloseIdleConnections)

	previous, err := loadGatewayConfig(context.Background(), client, string(data))
	if err != nil {
		t.Fatalf("Provider config publish through CaddyClient: %v", err)
	}
	if previous != previousJSON {
		t.Fatalf("previous config = %q, want %q", previous, previousJSON)
	}
	mu.Lock()
	got, contentType := received, receivedContentType
	mu.Unlock()
	if got != string(data) {
		t.Fatalf("Caddy Admin received config differs from Provider output: got=%q want=%q", got, string(data))
	}
	if contentType != "application/json" {
		t.Fatalf("Caddy Admin content type = %q, want application/json", contentType)
	}
	current, err := client.GetCurrentConfig(context.Background())
	if err != nil {
		t.Fatalf("read loaded Caddy Admin config: %v", err)
	}
	if current != string(data) {
		t.Fatalf("loaded Caddy Admin config differs from Provider output: got=%q want=%q", current, string(data))
	}
	wantHash, err := CanonicalConfigHash(string(data))
	if err != nil {
		t.Fatalf("canonicalize Provider config: %v", err)
	}
	gotHash, err := client.GetConfigHash(context.Background())
	if err != nil {
		t.Fatalf("hash loaded Caddy Admin config: %v", err)
	}
	if gotHash != wantHash {
		t.Fatalf("loaded Caddy Admin config hash = %s, want %s", gotHash, wantHash)
	}
	if err := os.WriteFile(out, []byte(got), 0600); err != nil {
		t.Fatalf("write Caddy Admin handoff: %v", err)
	}
}
